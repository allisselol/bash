// Backspace/Delete, Home/End, Ctrl+A/E/U/K/W, Ctrl+C (сбросить строку), Ctrl+D (конец ввода).
// Печатает приглашение prompt сам. Возвращает строку из malloc БЕЗ '\n' (освобождает вызывающий)
// или NULL при конце ввода (Ctrl+D на пустой строке / EOF).
// Непустая строка автоматически попадает в историю.
char* rl_readline(const char* prompt);

// освободить память истории (вызывать перед выходом из шелла)
void rl_history_free(void);
